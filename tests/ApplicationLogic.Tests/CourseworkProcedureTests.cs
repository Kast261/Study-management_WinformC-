        [Fact]
        public void StudentCrudKeepsClassAndAccountWhenAdminEditsPersonalFields()
        {
            using var db = CreateDatabase();
            int teacher = AddTeacher(); int classroom = AddClass(teacher);
            var service = new HocSinhService();
            var student = new HocSinh { HoTen = "Học viên ' thử", NgaySinh = new DateTime(2006, 4, 3) };
            Assert.True(service.Them(student, classroom));
            Assert.True(student.HocSinhID > 0);
            DatabaseHelper.ExecuteNonQuery("UPDATE HocSinh SET TaiKhoanID=777 WHERE HocSinhID=@id", new NpgsqlParameter("id", student.HocSinhID));
            student.HoTen = "  Tên mới ' tiếng Việt  ";student.NgaySinh = null;
