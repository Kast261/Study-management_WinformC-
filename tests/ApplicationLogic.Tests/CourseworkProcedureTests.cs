        [Fact]
        public async Task StudentCreationAndApprovalShareCapacityLock()
        {
            using var db = CreateDatabase();
            int teacher = AddTeacher();int classroom = AddClass(teacher);
            var waiting = new HocSinh { HoTen = "Đang chờ" };Assert.True(new HocSinhService().Them(waiting));
            int request = Convert.ToInt32(DatabaseHelper.ExecuteScalar(@"
                INSERT INTO DangKyLop (HocSinhID,LopHocID,TrangThai)
                VALUES (@hs,@lop,'Chờ duyệt') RETURNING DangKyID",
                new NpgsqlParameter("hs", waiting.HocSinhID), new NpgsqlParameter("lop", classroom)));
            var outcomes = await Task.WhenAll(
                Task.Run(() => new HocSinhService().Them(new HocSinh { HoTen = "Thêm trực tiếp" }, classroom)),
                Task.Run(() => new LopHocService().DuyetDangKy(request, classroom, waiting.HocSinhID, teacher)));
            Assert.Single(outcomes.Where(success => success));
            Assert.Equal(1L, DatabaseHelper.ExecuteScalar(@"
                SELECT COUNT(*) FROM HocSinh h WHERE h.LopHocID=@lop OR EXISTS (
                    SELECT 1 FROM DangKyLop dk WHERE dk.HocSinhID=h.HocSinhID
                    AND dk.LopHocID=@lop AND dk.TrangThai='Đã duyệt')", new NpgsqlParameter("lop", classroom)));
        }
