            Assert.True(service.Xoa(student.HocSinhID));
            Assert.False(service.Xoa(student.HocSinhID));
        }

        [Theory]
        [InlineData("course-class")]
        [InlineData("teacher-class")]
        [InlineData("teacher-exam")]
        [InlineData("teacher-account-forward")]
        [InlineData("teacher-account-reverse")]
        [InlineData("student-registration")]
        [InlineData("student-result")]
        [InlineData("student-account-forward")]
        [InlineData("student-account-reverse")]
        public void DeleteProceduresKeepReferencedData(string relation)
        {
            using var db = CreateDatabase();
            var courses = new KhoaHocService();var teachers = new GiaoVienService();var students = new HocSinhService();
            var course = new KhoaHoc { TenKhoaHoc = "Khóa đang dùng" };Assert.True(courses.Them(course));
            int teacher = AddTeacher();
            var student = new HocSinh { HoTen = "Người học" };Assert.True(students.Them(student));
            if (relation == "course-class")
                DatabaseHelper.ExecuteNonQuery("INSERT INTO LopHoc (TenLop,KhoaHocID) VALUES ('Lớp',@id)", new NpgsqlParameter("id", course.KhoaHocID));
            else if (relation == "teacher-class") AddClass(teacher);
            else if (relation == "teacher-exam")
                DatabaseHelper.ExecuteNonQuery("INSERT INTO DeThi (TenDeThi,ThoiGian,GiaoVienID) VALUES ('Đề',10,@id)", new NpgsqlParameter("id", teacher));
            else if (relation == "student-registration")
                DatabaseHelper.ExecuteNonQuery("INSERT INTO DangKyLop (HocSinhID,TrangThai) VALUES (@id,'Chờ duyệt')", new NpgsqlParameter("id", student.HocSinhID));
            else if (relation == "student-result")
                DatabaseHelper.ExecuteNonQuery("INSERT INTO KetQuaThi (HocSinhID,Diem) VALUES (@id,7.5)", new NpgsqlParameter("id", student.HocSinhID));
            else
            {
                bool isTeacher = relation.StartsWith("teacher");
                bool reverse = relation.EndsWith("reverse");
                int person = isTeacher ? teacher : student.HocSinhID;
                DatabaseHelper.ExecuteNonQuery(@"
                    INSERT INTO TaiKhoan (TaiKhoanID,TenDangNhap,MatKhau,VaiTro,NguoiDungID)
                    VALUES (99,'linked','test',@role,@person)",
                    new NpgsqlParameter("role", isTeacher ? "GiaoVien" : "HocVien"),
                    new NpgsqlParameter("person", reverse ? 0 : person));
                if (reverse)
                    DatabaseHelper.ExecuteNonQuery(isTeacher
                        ? "UPDATE GiaoVien SET TaiKhoanID=99 WHERE GiaoVienID=@id"
                        : "UPDATE HocSinh SET TaiKhoanID=99 WHERE HocSinhID=@id", new NpgsqlParameter("id", person));
            }
            var error = Assert.Throws<InvalidOperationException>(() =>
            {
                if (relation.StartsWith("course")) courses.Xoa(course.KhoaHocID);
                else if (relation.StartsWith("teacher")) teachers.Xoa(teacher);
                else students.Xoa(student.HocSinhID);
            });
            Assert.IsType<PostgresException>(error.InnerException);
            Assert.NotNull(courses.LayTheoID(course.KhoaHocID));
            Assert.NotNull(teachers.LayTheoID(teacher));
            Assert.NotNull(students.LayTheoID(student.HocSinhID));
        }

