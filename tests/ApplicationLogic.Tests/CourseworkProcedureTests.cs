        [Theory]
        [InlineData("course")]
        [InlineData("teacher")]
        [InlineData("student")]
        public void InvalidDataIsRejectedByDatabaseProcedureBeforeAnyInsert(string entity)
        {
            using var db = CreateDatabase();
            var error = Assert.Throws<PostgresException>(() =>
            {
                if (entity == "course") DatabaseHelper.ExecuteQuery("CALL study_them_khoa_hoc('', NULL, 0)");
                else if (entity == "teacher") new GiaoVienService().Them(new GiaoVien { HoTen = new string('x', 101) });
                else new HocSinhService().Them(new HocSinh { HoTen = "Hợp lệ", SoDienThoai = new string('1', 21) });
            });
            Assert.Equal("22023", error.SqlState);
            Assert.Equal(0L, DatabaseHelper.ExecuteScalar("SELECT COUNT(*) FROM KhoaHoc"));
            Assert.Equal(0L, DatabaseHelper.ExecuteScalar("SELECT COUNT(*) FROM GiaoVien"));
            Assert.Equal(0L, DatabaseHelper.ExecuteScalar("SELECT COUNT(*) FROM HocSinh"));
        }

        [Fact]
        public void CallerCanRollBackSeveralProcedureCallsTogether()
        {
            using var db = CreateDatabase();
            using var connection = DatabaseHelper.GetConnection();connection.Open();
            using (var transaction = connection.BeginTransaction())
            {
                using var command = new NpgsqlCommand(@"
                    CALL study_them_khoa_hoc('Không commit', NULL, 0);
                    CALL study_them_giao_vien('Giáo viên', NULL, NULL, NULL, NULL, NULL, NULL, 0);
                    CALL study_them_hoc_sinh('Học viên', NULL, NULL, NULL, NULL, NULL, 0, 0);", connection, transaction);
                command.ExecuteNonQuery();transaction.Rollback();
            }
            Assert.Equal(0L, DatabaseHelper.ExecuteScalar("SELECT COUNT(*) FROM KhoaHoc"));
            Assert.Equal(0L, DatabaseHelper.ExecuteScalar("SELECT COUNT(*) FROM GiaoVien"));
            Assert.Equal(0L, DatabaseHelper.ExecuteScalar("SELECT COUNT(*) FROM HocSinh"));
        }

