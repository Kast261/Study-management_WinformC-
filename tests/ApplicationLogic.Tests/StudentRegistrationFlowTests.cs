using System;
using System.Data;
using System.Linq;
using BLT_Quan_Ly_Hoc_Tap.DAL;
using BLT_Quan_Ly_Hoc_Tap.Database;
using BLT_Quan_Ly_Hoc_Tap.Models;
using Xunit;

namespace ApplicationLogic.Tests
{
    public class StudentRegistrationFlowTests
    {
        [Fact]
        public void StudentInSeveralClassesCanRegisterForNewMathClassAndSeeItsEarlierExamAfterApproval()
        {
            using var db = new LogicDatabase();
            DatabaseHelper.ExecuteNonQuery(@"
                ALTER TABLE LopHoc ALTER COLUMN LopHocID ADD GENERATED BY DEFAULT AS IDENTITY;
                SELECT setval(pg_get_serial_sequence('LopHoc','lophocid'),2);
                INSERT INTO DangKyLop (LopHocID,HocSinhID,TrangThai) VALUES (2,11,'Đã duyệt');");
            var classes = new LopHocDAL();
            Assert.True(classes.ThemLop(new LopHoc { TenLop = "Toán Lớp 2", GiaoVienID = 101,
                KhoaHocID = 1, SiSoToiDa = 40, TrangThai = "Đang mở", LichHoc = "T6 16h-18h" }));
            int mathClass = Convert.ToInt32(DatabaseHelper.ExecuteScalar("SELECT MAX(LopHocID) FROM LopHoc"));
            var exams = new DeThiDAL();
            int assignment = exams.TaoLanGiaoDeThi(2, 101, 1, mathClass, 45, DateTime.Now.AddDays(7));

            Assert.Contains(classes.LayLopChuaDangKy(11).Rows.Cast<DataRow>(), r => (int)r["LopHocID"] == mathClass);
            Assert.DoesNotContain(exams.LayDeThiChoHocSinh(11).Rows.Cast<DataRow>(), r => (int)r["DeThiID"] == assignment);
            Assert.True(classes.DangKyLop(mathClass, 11, out string message), message);
            Assert.DoesNotContain(classes.LayLopChuaDangKy(11).Rows.Cast<DataRow>(), r => (int)r["LopHocID"] == mathClass);
            int registration = Convert.ToInt32(DatabaseHelper.ExecuteScalar("SELECT MAX(DangKyID) FROM DangKyLop"));
            Assert.True(classes.DuyetDangKy(registration, mathClass, 11, 101));

            Assert.Equal(3, classes.LayTheoHocSinh(11).Rows.Count);
            Assert.Contains(exams.LayDeThiChoHocSinh(11).Rows.Cast<DataRow>(), r => (int)r["DeThiID"] == assignment);
            Assert.Contains(exams.LayBaiThiDangMoChoHocSinh(11).Rows.Cast<DataRow>(), r => (int)r["DeThiID"] == assignment);
            Assert.True(exams.CoTheBatDauThi(11, assignment));
            Assert.True(exams.CoTheBatDauThi(11, 1));
        }
    }
}
