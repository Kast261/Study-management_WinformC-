using System;
using System.Collections.Generic;
using System.Data;
using System.Linq;
using System.Threading.Tasks;
using BLT_Quan_Ly_Hoc_Tap.DAL;
using BLT_Quan_Ly_Hoc_Tap.Database;
using BLT_Quan_Ly_Hoc_Tap.Models;
using Xunit;

namespace ApplicationLogic.Tests
{
    public class AdminEnrollmentAndClassClosureTests
    {
        private static void EnableStudentCreation()
        {
            DatabaseHelper.ExecuteNonQuery(@"
                ALTER TABLE HocSinh ALTER COLUMN HocSinhID ADD GENERATED BY DEFAULT AS IDENTITY;
                SELECT setval(pg_get_serial_sequence('HocSinh','hocsinhid'),33);
                SELECT setval(pg_get_serial_sequence('TaiKhoan','taikhoanid'),3);");
        }

        [Fact]
        public void AdminCreatesStudentAndAccountInSelectedClassAndSeesEarlierExam()
        {
            using var db = new LogicDatabase();
            EnableStudentCreation();
            var exams = new DeThiDAL();
            int assigned = exams.TaoLanGiaoDeThi(2, 101, 1, 2, 45, null);
            var student = new HocSinh { HoTen = "Học viên mới" };
            Assert.True(new HocSinhDAL().Them(student, 2));
            Assert.True(student.HocSinhID > 33);
            var accounts = new TaiKhoanDAL();
            Assert.True(accounts.ThemTaiKhoan("new-student", "Example1", "HocSinh", student.HocSinhID));
            var login = accounts.DangNhap("new-student", "Example1");
            Assert.NotNull(login);
            int studentId = new HocSinhDAL().LayTheoTaiKhoan(login.TaiKhoanID).HocSinhID;
            Assert.Equal(student.HocSinhID, studentId);
            Assert.Equal(assigned, Assert.Single(exams.LayDeThiChoHocSinh(studentId).Rows.Cast<DataRow>())["DeThiID"]);
            Assert.Equal(assigned, Assert.Single(exams.LayBaiThiDangMoChoHocSinh(studentId).Rows.Cast<DataRow>())["DeThiID"]);
            Assert.False(exams.CoTheBatDauThi(studentId, 1));
            Assert.True(exams.CoTheBatDauThi(studentId, assigned));
            var answers = exams.LayDanhSachCauHoi(assigned).ToDictionary(q => q.CauHoiID, q => q.DapAnDung);
            Assert.Equal(10m, new KetQuaDAL().NopBai(login.TaiKhoanID, studentId, assigned, answers).Diem);
        }

        [Fact]
        public void UnassignedNewStudentDoesNotGainAccessToOtherClasses()
        {
            using var db = new LogicDatabase();
            EnableStudentCreation();
            var student = new HocSinh { HoTen = "Chưa xếp lớp" };
            Assert.True(new HocSinhDAL().Them(student));
            Assert.Empty(new DeThiDAL().LayDeThiChoHocSinh(student.HocSinhID).Rows);
            Assert.Empty(new LopHocDAL().LayTheoHocSinh(student.HocSinhID).Rows);
        }

        [Theory]
        [InlineData(999, "SELECT 1")]
        [InlineData(2, "UPDATE LopHoc SET TrangThai='Đã đóng' WHERE LopHocID=2")]
        [InlineData(2, "UPDATE LopHoc SET SiSoToiDa=0 WHERE LopHocID=2")]
        [InlineData(1, "UPDATE LopHoc SET SiSoToiDa=1 WHERE LopHocID=1")]
        public void InvalidClassCannotLeaveAPartiallyCreatedStudent(int target, string sql)
        {
            using var db = new LogicDatabase();
            EnableStudentCreation();
            DatabaseHelper.ExecuteNonQuery(sql);
            var student = new HocSinh { HoTen = "Không được thêm" };
            Assert.False(new HocSinhDAL().Them(student, target));
            Assert.Equal(0, student.HocSinhID);
            Assert.Equal(3L, DatabaseHelper.ExecuteScalar("SELECT COUNT(*) FROM HocSinh"));
        }

        [Fact]
        public async Task ConcurrentAdminAddsCannotExceedClassCapacity()
        {
            using var db = new LogicDatabase();
            EnableStudentCreation();
            DatabaseHelper.ExecuteNonQuery("UPDATE LopHoc SET SiSoToiDa=1 WHERE LopHocID=2");
            var outcomes = await Task.WhenAll(Enumerable.Range(0, 4).Select(i => Task.Run(() =>
                new HocSinhDAL().Them(new HocSinh { HoTen = "Mới " + i }, 2))));
            Assert.Single(outcomes.Where(success => success));
            Assert.Equal(1L, DatabaseHelper.ExecuteScalar("SELECT COUNT(*) FROM HocSinh WHERE LopHocID=2"));
        }

        [Fact]
        public void ClosingOneNamesakeClassKeepsOtherClassesOpenAndExistingExamsAccessible()
        {
            using var db = new LogicDatabase();
            DatabaseHelper.ExecuteNonQuery(@"
                UPDATE LopHoc SET TenLop='Lớp trùng tên';
                INSERT INTO LopHoc (LopHocID,TenLop,GiaoVienID,KhoaHocID,TrangThai)
                    VALUES (3,'Lớp trùng tên',202,1,'Đang mở');");
            var classes = new LopHocDAL();
            Assert.True(classes.DongDangKyLop(1, 101));
            Assert.Equal("Đã đóng", DatabaseHelper.ExecuteScalar("SELECT TrangThai FROM LopHoc WHERE LopHocID=1"));
            Assert.Equal(2L, DatabaseHelper.ExecuteScalar("SELECT COUNT(*) FROM LopHoc WHERE TrangThai='Đang mở'"));
            Assert.False(classes.DongDangKyLop(3, 101));
            Assert.False(classes.DongDangKyLop(0, 101));
            Assert.False(classes.DongDangKyLop(1, 101));
            using var available = classes.LayLopChuaDangKy(22);
            Assert.Equal(new[] { 2, 3 }, available.Rows.Cast<DataRow>().Select(r => (int)r["LopHocID"]).OrderBy(id => id));
            Assert.False(classes.DangKyLop(1, 22, out _));
            Assert.True(classes.DangKyLop(2, 22, out _));
            Assert.True(new DeThiDAL().CoTheBatDauThi(11, 1));
            Assert.Single(new DeThiDAL().LayBaiThiDangMoChoHocSinh(11).Rows);
        }
    }
}
