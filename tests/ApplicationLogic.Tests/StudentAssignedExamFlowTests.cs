        [Fact]
        public void ApprovingAnotherClassDoesNotRemoveOriginalClassOrItsAssignments()
        {
            using var db = new LogicDatabase();
            var classes = new LopHocDAL();
            var exams = new DeThiDAL();
            Assert.True(classes.DangKyLop(2, 11, out _));
            int registration = Convert.ToInt32(DatabaseHelper.ExecuteScalar("SELECT DangKyID FROM DangKyLop WHERE HocSinhID=11"));
            int newClassExam = exams.TaoLanGiaoDeThi(2, 101, 1, 2, 45, null);
            Assert.True(classes.DuyetDangKy(registration, 2, 11, 101));

            Assert.Equal(1, DatabaseHelper.ExecuteScalar("SELECT LopHocID FROM HocSinh WHERE HocSinhID=11"));
            Assert.Equal(new[] { 1, 2 }, Ids(classes.LayTheoHocSinh(11), "LopHocID"));
            Assert.Equal(new[] { 1, newClassExam }, Ids(exams.LayDeThiChoHocSinh(11), "DeThiID"));
            Assert.Equal(new[] { 1, newClassExam }, Ids(exams.LayBaiThiDangMoChoHocSinh(11), "DeThiID"));
            Assert.True(exams.CoTheBatDauThi(11, 1));
            Assert.True(exams.CoTheBatDauThi(11, newClassExam));
        }

        [Theory]
        [InlineData(true)]
        [InlineData(false)]
        public void AccountsAndClassCreatedThroughRepositoriesCanSeeAssignedExam(bool approveBeforeAssigning)
        {
            using var db = new LogicDatabase();
            DatabaseHelper.ExecuteNonQuery(@"
                ALTER TABLE GiaoVien ALTER COLUMN GiaoVienID ADD GENERATED BY DEFAULT AS IDENTITY;
                ALTER TABLE HocSinh ALTER COLUMN HocSinhID ADD GENERATED BY DEFAULT AS IDENTITY;
                ALTER TABLE LopHoc ALTER COLUMN LopHocID ADD GENERATED BY DEFAULT AS IDENTITY;
                SELECT setval(pg_get_serial_sequence('GiaoVien','giaovienid'),101);
                SELECT setval(pg_get_serial_sequence('HocSinh','hocsinhid'),33);
                SELECT setval(pg_get_serial_sequence('LopHoc','lophocid'),2);
                SELECT setval(pg_get_serial_sequence('TaiKhoan','taikhoanid'),3);");
            var teachers = new GiaoVienDAL();
            var students = new HocSinhDAL();
            var accounts = new TaiKhoanDAL();
            var classes = new LopHocDAL();
            var exams = new DeThiDAL();
            Assert.True(teachers.Them(new GiaoVien { HoTen = "Hằng", ChuyenMon = "Toán" }));
            Assert.True(students.Them(new HocSinh { HoTen = "Hùng" }));
            int teacherId = Convert.ToInt32(DatabaseHelper.ExecuteScalar("SELECT MAX(GiaoVienID) FROM GiaoVien"));
            int studentId = Convert.ToInt32(DatabaseHelper.ExecuteScalar("SELECT MAX(HocSinhID) FROM HocSinh"));
            Assert.True(accounts.ThemTaiKhoan("HangGiaoVien", "Example1", "GiaoVien", teacherId));
            Assert.True(accounts.ThemTaiKhoan("HungHocVien", "Example1", "HocSinh", studentId));
            var teacher = accounts.DangNhap("HangGiaoVien", "Example1");
            var student = accounts.DangNhap("HungHocVien", "Example1");
            Assert.Equal(teacherId, teacher.NguoiDungID);
            Assert.Equal(studentId, students.LayTheoTaiKhoan(student.TaiKhoanID).HocSinhID);
            Assert.NotEqual(student.TaiKhoanID, student.NguoiDungID);
            Assert.True(classes.ThemLop(new LopHoc { TenLop = "Toán Lớp 2", KhoaHocID = 1,
                GiaoVienID = teacherId, SiSoToiDa = 30, TrangThai = "Đang mở" }));
            int classId = Convert.ToInt32(DatabaseHelper.ExecuteScalar("SELECT MAX(LopHocID) FROM LopHoc"));
            int sourceId = exams.TaoDeThiMoiLayID(new DeThi { TenDeThi = "Đề Toán mới", MonHoc = "Toán",
                GiaoVienID = teacher.NguoiDungID, ThoiGian = 45, SoCau = 0, TrangThai = "Chưa giao" });
            Assert.True(exams.ThemCauHoi(new CauHoi { DeThiID = sourceId, NoiDung = "1 + 1 = ?",
                DapAnA = "1", DapAnB = "2", DapAnC = "3", DapAnD = "4", DapAnDung = "B" }, teacherId));
            Assert.True(classes.DangKyLop(classId, student.NguoiDungID, out _));
            int registration = Convert.ToInt32(DatabaseHelper.ExecuteScalar("SELECT DangKyID FROM DangKyLop WHERE HocSinhID=@hs",
                new NpgsqlParameter("hs", student.NguoiDungID)));
            if (approveBeforeAssigning) Assert.True(classes.DuyetDangKy(registration, classId, studentId, teacherId));
            int assignment = exams.TaoLanGiaoDeThi(teacher.TaiKhoanID, teacher.NguoiDungID, sourceId, classId, 45, DateTime.Now.AddDays(7), "Toán");
            if (!approveBeforeAssigning)
            {
                Assert.Empty(exams.LayDeThiChoHocSinh(studentId).Rows);
                Assert.True(classes.DuyetDangKy(registration, classId, studentId, teacherId));
            }
            Assert.Equal(new[] { assignment }, Ids(exams.LayDeThiChoHocSinh(studentId), "DeThiID"));
            Assert.Equal(new[] { assignment }, Ids(exams.LayBaiThiDangMoChoHocSinh(studentId), "DeThiID"));
            Assert.Equal("Toán Lớp 2", exams.LayDeThiChoHocSinh(studentId).Rows[0]["TenLop"]);
            Assert.True(exams.CoTheBatDauThi(studentId, assignment));
            using var report = Diagnose();
            Assert.Equal("Đủ điều kiện hiện bài thi", Assert.Single(report.Rows.Cast<DataRow>())["ChanDoan"]);
        }

        [Fact]
        public void ClassesWithIdenticalNamesKeepSeparateMembershipAndExamAccess()
        {
            using var db = new LogicDatabase();
            DatabaseHelper.ExecuteNonQuery(@"
                UPDATE TaiKhoan SET TenDangNhap='HungHocVien' WHERE TaiKhoanID=3;
                UPDATE LopHoc SET TenLop='Toán Lớp 2' WHERE LopHocID=2;
                INSERT INTO LopHoc (LopHocID,TenLop,GiaoVienID,KhoaHocID)
                    VALUES (3,'Toán Lớp 2',101,1);");
            var classes = new LopHocDAL();
            var exams = new DeThiDAL();
            Assert.True(classes.DangKyLop(2, 22, out _));
            int registration = Convert.ToInt32(DatabaseHelper.ExecuteScalar("SELECT DangKyID FROM DangKyLop WHERE HocSinhID=22"));
            Assert.True(classes.DuyetDangKy(registration, 2, 22, 101));
            int otherClassExam = exams.TaoLanGiaoDeThi(2, 101, 1, 3, 45, null);
            Assert.Empty(exams.LayDeThiChoHocSinh(22).Rows);
            Assert.False(exams.CoTheBatDauThi(22, otherClassExam));
            using var report = Diagnose();
            Assert.Equal("Học viên chưa thuộc mã lớp này: kiểm tra lớp trùng tên",
                report.Rows.Cast<DataRow>().Single(row => Convert.ToInt32(row["LopHocID"]) == 3)["ChanDoan"]);
            Assert.Equal("Chưa có lượt đề thi được lưu cho mã lớp này",
                report.Rows.Cast<DataRow>().Single(row => Convert.ToInt32(row["LopHocID"]) == 2)["ChanDoan"]);
            int correctClassExam = exams.TaoLanGiaoDeThi(2, 101, 1, 2, 45, null);
            Assert.Equal(new[] { correctClassExam }, Ids(exams.LayDeThiChoHocSinh(22), "DeThiID"));
        }

        private static int[] Ids(DataTable table, string column) => table.Rows.Cast<DataRow>()
            .Select(row => Convert.ToInt32(row[column])).OrderBy(id => id).ToArray();

        private static DataTable Diagnose()
        {
            using var stream = typeof(StudentAssignedExamFlowTests).Assembly.GetManifestResourceStream("DiagnoseStudentExams.sql");
            using var reader = new StreamReader(stream);
            return DatabaseHelper.ExecuteQuery(reader.ReadToEnd());
        }
    }
