using System;
using BLT_Quan_Ly_Hoc_Tap.Database;
using Npgsql;
using StudentProfile.Tests;

namespace ExcelImport.Tests
{
    internal sealed class ImportDatabase : IDisposable
    {
        private readonly TestDatabase database = new TestDatabase();

        public ImportDatabase()
        {
            DatabaseHelper.ExecuteNonQuery(@"
                CREATE TABLE GiaoVien (GiaoVienID integer PRIMARY KEY, TaiKhoanID integer);
                CREATE TABLE DeThi (
                    DeThiID integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    GiaoVienID integer, TenDeThi varchar(150), MonHoc varchar(100),
                    SoCau integer DEFAULT 0, ThoiGian integer DEFAULT 45,
                    TrangThai varchar(50), LopHocID integer);
                CREATE TABLE CauHoi (
                    CauHoiID integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    DeThiID integer REFERENCES DeThi(DeThiID),
                    NoiDung text NOT NULL CHECK (NoiDung <> 'DB_REJECT'),
                    DapAnA varchar(255) NOT NULL, DapAnB varchar(255) NOT NULL,
                    DapAnC varchar(255) NOT NULL, DapAnD varchar(255) NOT NULL,
                    DapAnDung varchar(5), ThuTu integer);
                CREATE TABLE KetQuaThi (KetQuaID integer PRIMARY KEY, DeThiID integer);");
            database.SeedAccount(1, 11, "GiaoVien");
            database.SeedAccount(2, 22, "GiaoVien");
            DatabaseHelper.ExecuteNonQuery("INSERT INTO GiaoVien VALUES (11,1),(22,2)");
        }

        public static int CreateExam(int teacherId = 11, int? classId = null)
        {
            return Convert.ToInt32(DatabaseHelper.ExecuteScalar(@"
                INSERT INTO DeThi (GiaoVienID, TenDeThi, MonHoc, TrangThai, LopHocID)
                VALUES (@gv, 'Đề cũ', 'C#', 'Chưa giao', @lop) RETURNING DeThiID",
                new NpgsqlParameter("gv", teacherId),
                new NpgsqlParameter("lop", NpgsqlTypes.NpgsqlDbType.Integer) { Value = (object)classId ?? DBNull.Value }));
        }

        public static void AddOldQuestion(int examId, int order)
        {
            DatabaseHelper.ExecuteNonQuery(@"
                INSERT INTO CauHoi (DeThiID, NoiDung, DapAnA, DapAnB, DapAnC, DapAnD, DapAnDung, ThuTu)
                VALUES (@id, 'Câu hỏi cũ', 'A', 'B', 'C', 'D', 'A', @order)",
                new NpgsqlParameter("id", examId), new NpgsqlParameter("order", order));
        }

        public void Dispose() => database.Dispose();
    }
}
